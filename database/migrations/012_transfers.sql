CREATE TABLE IF NOT EXISTS transfers (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  transfer_code VARCHAR(36) NOT NULL DEFAULT '',
  company_id BIGINT UNSIGNED NOT NULL,
  company_name_snapshot VARCHAR(255) NOT NULL,
  company_role_snapshot VARCHAR(20) NOT NULL,
  period_type ENUM('weekly','monthly','custom') NOT NULL,
  period_start DATE NOT NULL,
  period_end DATE NOT NULL,
  member_win_total DECIMAL(24,6) NOT NULL,
  site_usd_calculated DECIMAL(24,6) NOT NULL,
  site_usd_applied DECIMAL(24,6) NOT NULL,
  override_reason TEXT NULL,
  transfer_percent DECIMAL(9,3) NOT NULL,
  usd_share DECIMAL(24,6) NOT NULL,
  usd_rate_toman DECIMAL(24,6) NOT NULL,
  total_toman DECIMAL(24,6) NOT NULL,
  direction ENUM('to_master','from_master','none') NOT NULL,
  report_count INT UNSIGNED NOT NULL,
  notes TEXT NULL,
  status ENUM('final','void') NOT NULL DEFAULT 'final',
  revision_no INT UNSIGNED NOT NULL DEFAULT 1,
  created_by BIGINT UNSIGNED NULL,
  updated_by BIGINT UNSIGNED NULL,
  voided_by BIGINT UNSIGNED NULL,
  void_reason TEXT NULL,
  voided_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_transfer_company_period (company_id,period_start,period_end),
  KEY idx_transfer_status_created (status,created_at),
  CONSTRAINT fk_transfer_company FOREIGN KEY(company_id) REFERENCES companies(id) ON DELETE RESTRICT,
  CONSTRAINT fk_transfer_creator FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS transfer_report_items (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  transfer_id BIGINT UNSIGNED NOT NULL,
  daily_report_id BIGINT UNSIGNED NOT NULL,
  report_date DATE NOT NULL,
  member_win_snapshot DECIMAL(24,6) NOT NULL,
  UNIQUE KEY uniq_transfer_report (transfer_id,daily_report_id),
  KEY idx_transfer_source_report (daily_report_id),
  CONSTRAINT fk_tri_transfer FOREIGN KEY(transfer_id) REFERENCES transfers(id) ON DELETE CASCADE,
  CONSTRAINT fk_tri_report FOREIGN KEY(daily_report_id) REFERENCES daily_reports(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS transfer_revisions (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  transfer_id BIGINT UNSIGNED NOT NULL,
  action_type ENUM('created','updated','voided') NOT NULL,
  before_json LONGTEXT NULL,
  after_json LONGTEXT NULL,
  reason TEXT NULL,
  changed_by BIGINT UNSIGNED NULL,
  changed_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_transfer_revisions (transfer_id,changed_at),
  CONSTRAINT fk_trv_transfer FOREIGN KEY(transfer_id) REFERENCES transfers(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
